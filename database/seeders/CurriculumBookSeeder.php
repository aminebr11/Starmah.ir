<?php

namespace Database\Seeders;

use App\Models\CurriculumBook;
use App\Support\Levels;
use Illuminate\Database\Seeder;

/** دروس پیش‌فرض هر پایه (ادمین کل می‌تواند ویرایش/کم/زیاد کند). */
class CurriculumBookSeeder extends Seeder
{
    public function run(): void
    {
        // دروس رایج هر مقطع
        $byLevel = [
            'دبستان' => [
                ['ریاضی', '🧮'], ['فارسی', '📖'], ['علوم', '🔬'], ['مطالعات اجتماعی', '🌍'],
                ['قرآن', '📗'], ['هدیه‌های آسمانی', '🕌'], ['هنر', '🎨'], ['ورزش', '🏃'],
            ],
            'متوسطه اول' => [
                ['ریاضی', '🧮'], ['علوم تجربی', '🔬'], ['فارسی', '📖'], ['نگارش', '✍️'],
                ['مطالعات اجتماعی', '🌍'], ['عربی', '🕌'], ['زبان انگلیسی', '🔤'], ['پیام‌های آسمان', '📗'],
                ['کار و فناوری', '💻'], ['تفکر و سبک زندگی', '🧠'], ['فرهنگ و هنر', '🎨'], ['ورزش', '🏃'],
            ],
            'متوسطه دوم' => [
                ['ریاضی', '🧮'], ['فیزیک', '🧲'], ['شیمی', '⚗️'], ['زیست‌شناسی', '🧬'],
                ['ادبیات فارسی', '📖'], ['عربی', '🕌'], ['زبان انگلیسی', '🔤'], ['دینی', '📗'],
                ['تاریخ', '📜'], ['جغرافیا', '🗺️'], ['هندسه', '📐'], ['حسابان', '📈'],
            ],
        ];

        foreach ($byLevel as $level => $books) {
            foreach (Levels::grades($level) as $grade) {
                foreach ($books as $i => [$name, $icon]) {
                    CurriculumBook::firstOrCreate(
                        ['level' => $level, 'grade' => $grade, 'name' => $name],
                        ['icon' => $icon, 'sort' => $i]
                    );
                }
            }
        }
    }
}
