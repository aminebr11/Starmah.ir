<?php

namespace App\Support;

/** متنِ فارسیِ خطاهای HTTP برای صفحه‌ی خطا و پاسخ‌های JSON. */
class ErrorMessages
{
    /** @return array{title:string,text:string}|null */
    public static function for(int $status): ?array
    {
        return match ($status) {
            401 => ['title' => 'اول وارد شوید', 'text' => 'برای دیدنِ این صفحه باید وارد حسابِ کاربری شوید.'],
            403 => ['title' => 'دسترسی ندارید', 'text' => 'اجازه‌ی دیدنِ این بخش را ندارید. اگر فکر می‌کنید اشتباه است، به مدیرِ مدرسه خبر بدهید.'],
            404 => ['title' => 'صفحه پیدا نشد', 'text' => 'این صفحه وجود ندارد یا جابه‌جا شده است.'],
            405 => ['title' => 'درخواستِ نامعتبر', 'text' => 'این کار از این راه انجام نمی‌شود. صفحه را تازه کنید و دوباره امتحان کنید.'],
            413 => ['title' => 'فایل خیلی بزرگ است', 'text' => 'حجمِ فایل بیش از حدِ مجاز است. فایلِ کوچک‌تری انتخاب کنید.'],
            419 => ['title' => 'زمانِ صفحه تمام شد', 'text' => 'مدتی گذشته و صفحه منقضی شد. یک‌بار صفحه را تازه کنید و دوباره امتحان کنید.'],
            429 => ['title' => 'کمی صبر کنید', 'text' => 'در زمانِ کوتاهی درخواستِ زیادی فرستاده شد. چند لحظه صبر کنید و دوباره امتحان کنید.'],
            500 => ['title' => 'خطای سرور', 'text' => 'مشکلی در سرور پیش آمد. چند لحظه بعد دوباره امتحان کنید؛ اگر تکرار شد به پشتیبانی خبر بدهید.'],
            502, 504 => ['title' => 'سرور پاسخ نداد', 'text' => 'اتصال به سرور برقرار نشد. چند لحظه بعد دوباره امتحان کنید.'],
            503 => ['title' => 'در حالِ به‌روزرسانی', 'text' => 'سایت چند دقیقه در حالِ به‌روزرسانی است. کمی بعد برگردید.'],
            default => null,
        };
    }
}
